/* 九九の読み (句) の単一の出どころ。
   けいさんの九九暗唱 (gKukuYomi) と 木漏れ日の小道 の段暗唱・れんぞく九九 が
   同じ読みを使う。表を 2 か所に持つと片方だけ直る (実際 2×1 の読みは
   「ににんがに」から「にいちがに」へ一度訂正が入っている)。 */
(function(global){
  "use strict";

  /* 各段 9 句。index 0 が ×1。 */
  var TABLE={
    1:["いんいちがいち","いんにがに","いんさんがさん","いんしがし","いんごがご","いんろくがろく","いんしちがしち","いんはちがはち","いんくがく"],
    2:["にいちがに","ににんがし","にさんがろく","にしがはち","にごじゅう","にろくじゅうに","にしちじゅうし","にはちじゅうろく","にくじゅうはち"],
    3:["さんいちがさん","さんにがろく","さざんがく","さんしじゅうに","さんごじゅうご","さぶろくじゅうはち","さんしちにじゅういち","さんぱにじゅうし","さんくにじゅうしち"],
    4:["しいちがし","しにがはち","しさんじゅうに","ししじゅうろく","しごにじゅう","しろくにじゅうし","ししちにじゅうはち","しはさんじゅうに","しくさんじゅうろく"],
    5:["ごいちがご","ごにじゅう","ごさんじゅうご","ごしにじゅう","ごごにじゅうご","ごろくさんじゅう","ごしちさんじゅうご","ごはしじゅう","ごっくしじゅうご"],
    6:["ろくいちがろく","ろくにじゅうに","ろくさんじゅうはち","ろくしにじゅうし","ろくごさんじゅう","ろくろくさんじゅうろく","ろくしちしじゅうに","ろくはしじゅうはち","ろっくごじゅうし"],
    7:["しちいちがしち","しちにじゅうし","しちさんにじゅういち","しちしにじゅうはち","しちごさんじゅうご","しちろくしじゅうに","しちしちしじゅうく","しちはごじゅうろく","しちくろくじゅうさん"],
    8:["はちいちがはち","はちにじゅうろく","はっさんにじゅうし","はちしさんじゅうに","はちごしじゅう","はちろくしじゅうはち","はちしちごじゅうろく","はっぱろくじゅうし","はっくしちじゅうに"],
    9:["くいちがく","くにじゅうはち","くさんにじゅうしち","くしさんじゅうろく","くごしじゅうご","くろくごじゅうし","くしちろくじゅうさん","くはしちじゅうに","くくはちじゅういち"]
  };
  /* 学校の指導順。段暗唱・れんぞく九九のカテゴリ解禁順もこれに従う。 */
  var TEACHING_ORDER=[2,5,3,4,6,7,8,9,1];

  function phrase(dan,b){
    if(!Number.isInteger(dan)||!Number.isInteger(b)||!TABLE[dan]||b<1||b>9)throw new Error("九九の読みの指定が正しくありません");
    return TABLE[dan][b-1];
  }
  function phrasesFor(dan){
    if(!TABLE[dan])throw new Error("九九の読みの指定が正しくありません");
    return TABLE[dan].slice();
  }

  global.Q4B_KUKU_PHRASES={
    table:TABLE,
    teachingOrder:TEACHING_ORDER.slice(),
    phrase:phrase,
    phrasesFor:phrasesFor
  };
})(typeof window!=="undefined"?window:globalThis);
